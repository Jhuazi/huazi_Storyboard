def main():
    parser = argparse.ArgumentParser(description="创建分镜图设定项目骨架")
    parser.add_argument("name", help="项目名称(小说名或指定名称)")
    parser.add_argument("--path", default=".", help="输出目录，默认当前工作目录")
    args = parser.parse_args()

    folder = os.path.join(args.path, f"{args.name}分镜图设定")
    if os.path.exists(folder) and os.listdir(folder):
        print(f"⚠️ 目录已存在且非空: {folder}")
        sys.exit(1)
    os.makedirs(folder, exist_ok=True)
    date = datetime.date.today().isoformat()
    for fname, content in FILES.items():
        with open(os.path.join(folder, fname), "w", encoding="utf-8") as f:
            f.write(content.replace("{名称}", args.name).replace("{date}", date))
    print(f"✅ 已创建项目: {folder}")
    for fname in FILES:
        print(f"   - {fname}")


if __name__ == "__main__":
    main()
